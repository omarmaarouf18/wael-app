let lang = DEFAULT_LANG;
const listeners = new Set();

export function getLang() {
  return lang;
}

export function dirOf(l = lang) {
  return DIRS[l] ?? DIRS[DEFAULT_LANG];
}

/** Returns the language named by a location hash ("#en"), else the default. */
export function langFromHash(hash) {
  const name = String(hash ?? '').replace(/^#/, '');
  return LANGS.includes(name) ? name : DEFAULT_LANG;
}

export function setLang(next) {
  if (!LANGS.includes(next)) return false;
  lang = next;
  for (const cb of listeners) cb(next);
  return true;
}

export function otherLang(l = lang) {
  return l === 'ar' ? 'en' : 'ar';
}

/** Subscribes to language changes; returns an unsubscribe function. */
export function onLangChange(cb) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

/** Looks a key up in the current language, then English, then returns the key. */
export function t(key, params) {
  const raw = MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
}

/**
 * Text for a failed request. A known server error code wins over the status
 * kind; anything unknown falls back to the kind. Server text is never shown.
 */
export function errorText(code, kind) {
  const key = typeof code === 'string' && code ? `err.${code}` : null;
  if (key && (key in MESSAGES.ar || key in MESSAGES.en)) return t(key);
  return t(`err.${kind}`);
}

/**
 * Translates every data-i18n* element under root and sets lang/dir on the
 * document element. Supported attributes: data-i18n (text),
 * data-i18n-placeholder, data-i18n-aria-label.
 */
export function applyTranslations(root) {
  const doc = root.ownerDocument ?? root;
  doc.documentElement.lang = lang;
  doc.documentElement.dir = dirOf(lang);
  doc.title = t('app.title');
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  }
  for (const el of root.querySelectorAll('[data-i18n-aria-label]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
  }
}

// ---------------------------------------------------------------------------
// Numerals (owner 2026-11-14): one rule for the whole console, and this is the
// only place that applies it. Dates, times, counts and amounts follow the page
// language: Arabic-Indic digits (ar-EG) in Arabic, Latin digits in English.
// Phone numbers, emails, ids, product ids and transaction ids are never passed
// through these helpers: they are shown as typed, Latin and left-to-right
// (class "ltr"), in both languages.
// ---------------------------------------------------------------------------

/** The Intl locale for the page language. */
export function locale(l = lang) {
  return l === 'ar' ? 'ar-EG' : 'en-GB';
}

function formatWith(value, options) {
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return '';
  return new Intl.DateTimeFormat(locale(), { timeZone: 'Africa/Cairo', ...options }).format(d);
}

export function formatDate(value) {
  return formatWith(value, { dateStyle: 'medium' });
}

export function formatTime(value) {
  return formatWith(value, { timeStyle: 'short' });
}

export function formatNumber(n) {
  return new Intl.NumberFormat(locale()).format(n);
}

/** An amount in Egyptian pounds, e.g. "١٬٦٥٠ جنيه" / "1,650 EGP". */
export function formatMoney(n) {
  const value = Number(n);
  return t('catalog.price', { n: formatNumber(Number.isFinite(value) ? value : 0) });
}

/** A Cairo calendar date in the page language (medium style), '' when invalid. */
export function formatCairoDate(value) {
  return formatWith(value, { dateStyle: 'medium' });
}

/**
 * How long ago an instant was, e.g. "منذ يومين" / "2 days ago". Minutes under
 * an hour, hours under a day, days after that. '' for an invalid value.
 */
export function formatAge(value, now = new Date()) {
  const then = new Date(value).getTime();
  if (Number.isNaN(then)) return '';
  const minutes = Math.max(0, Math.round((now.getTime() - then) / 60000));
  const rtf = new Intl.RelativeTimeFormat(locale(), { numeric: 'auto' });
  if (minutes < 60) return rtf.format(-minutes, 'minute');
  const hours = Math.round(minutes / 60);
  if (hours < 24) return rtf.format(-hours, 'hour');
  return rtf.format(-Math.round(hours / 24), 'day');
}

/** Long date for day headers, e.g. "Friday, 13 November 2026". */
export function formatLongDate(value) {
  return formatWith(value, { dateStyle: 'full' });
}

/** Calendar day in Cairo as YYYY-MM-DD, or '' for an invalid value. */
export function cairoDayKey(value) {
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return '';
  return new Intl.DateTimeFormat('en-CA', { timeZone: 'Africa/Cairo', year: 'numeric', month: '2-digit', day: '2-digit' }).format(d);
}

export function formatCairoDateTime(value) {
  return formatWith(value, { dateStyle: 'medium', timeStyle: 'short' });
}
